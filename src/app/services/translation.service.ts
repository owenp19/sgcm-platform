// Merge additional languages into TRANSLATIONS
Object.assign(TRANSLATIONS, { fr: FR, pt: PT, it: IT, zh: ZH });

@Injectable({ providedIn: 'root' })
export class TranslationService {
  private readonly LANG_KEY = 'occre_lang';
  private _current: Language = 'es';
  private listeners: Array<() => void> = [];

  constructor() {
    const stored = localStorage.getItem(this.LANG_KEY) as Language | null;
    if (stored && ['es', 'en', 'fr', 'pt', 'it', 'zh'].includes(stored)) {
      this._current = stored;
    }
  }

  get current(): Language {
    return this._current;
  }

  get translations(): Record<string, string> {
    return TRANSLATIONS[this._current];
  }

  translate(key: string): string {
    return this.translations[key] ?? key;
  }

  setLanguage(lang: Language): void {
    if (lang === this._current) return;
    this._current = lang;
    localStorage.setItem(this.LANG_KEY, lang);
    this.listeners.forEach(fn => fn());
  }

  get supportedLanguages(): Language[] {
    return ['es', 'en', 'fr', 'pt', 'it', 'zh'];
  }

  get languageNames(): Record<Language, string> {
    return LANG_NAMES;
  }

  toggleLanguage(): void {
    const langs = this.supportedLanguages;
    const idx = langs.indexOf(this._current);
    this.setLanguage(langs[(idx + 1) % langs.length]);
  }

  onChange(fn: () => void): () => void {
    this.listeners.push(fn);
    return () => {
      this.listeners = this.listeners.filter(l => l !== fn);
    };
  }
}
